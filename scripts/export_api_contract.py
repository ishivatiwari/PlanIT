"""Generate frontend contracts from the actual FastAPI OpenAPI schema."""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services/api"))

from app.core.settings import Settings  # noqa: E402
from app.main import create_app  # noqa: E402


def typescript(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        required = set(schema.get("required", []))
        fields = [
            f"  {json.dumps(key)}{'' if key in required else '?'}: {typescript(value)};"
            for key, value in schema.get("properties", {}).items()
        ]
        return "{\n" + "\n".join(fields) + "\n}" if fields else "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    app = create_app(
        Settings(
            _env_file=None,
            database_url="postgresql+psycopg://contract:unused@127.0.0.1/contract",
            app_env="test",
        )
    )
    schemas = app.openapi()["components"]["schemas"]
    output = "// Generated by scripts/export_api_contract.py. Do not edit by hand.\n\n"
    output += (
        "\n\n".join(
            f"export type {name} = {typescript(schema)};"
            for name, schema in sorted(schemas.items())
        )
        + "\n"
    )
    target = ROOT / "apps/web/src/lib/api-types.ts"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != output:
            raise SystemExit("API types are stale. Run scripts/export_api_contract.py.")
        print("PASS: frontend contracts match FastAPI OpenAPI.")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(output, encoding="utf-8", newline="\n")
        print("Generated frontend API types.")


if __name__ == "__main__":
    main()
